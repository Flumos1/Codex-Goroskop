    f = rule.get('factor', {})
    key = (f.get('planet'), f.get('sign'))
    if key in PATCHES:
        s_ru, p_ru, g_ru, r_ru = PATCHES[key]
        if 'simpleRu' not in rule:
            rule['simpleRu'] = {}
        rule['simpleRu']['summary']    = s_ru
        rule['simpleRu']['pattern']    = p_ru
        rule['simpleRu']['growth']     = g_ru
        rule['simpleRu']['reflection'] = r_ru
        patched += 1

